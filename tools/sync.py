#!/usr/bin/env python3
"""Rebuild js/templates.js from the design canvas source files.

Usage:  python3 tools/sync.py
Reads   source/*.dc.html   (copies of the artboards from the AJPVC Launch Creative Kit canvas)
Writes  js/templates.js    (the templates the app fills with each location's details)

Location fields become {{TOKENS}}; images that point at the canvas asset store are
mapped to files in assets/ using tools/pieces.json. An image the map doesn't know
stops the sync, so a new picture added on the canvas is never silently dropped.
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cfg = json.load(open(os.path.join(ROOT, 'tools', 'pieces.json')))


def extract(html):
    body = html.split('<x-dc>', 1)[1].split('</x-dc>', 1)[0]
    body = re.sub(r'<helmet>.*?</helmet>', '', body, flags=re.S)
    return body.strip()


def page_size(html):
    m = re.search(r'"\$preview":\{"width":(\d+),"height":(\d+)\}', html)
    return int(m.group(1)), int(m.group(2))


def map_assets(body, fname):
    def sub(m):
        bid = m.group(1)
        if bid not in cfg['assets']:
            sys.exit(f'Unknown image {bid} in {fname}: download it into assets/ and add it to tools/pieces.json')
        return 'assets/' + cfg['assets'][bid]
    return re.sub(r'/_blob/([0-9a-f]{32})', sub, body)


out = []
for piece in cfg['pieces']:
    if piece.get('kind') == 'file':      # a finished, print-ready file supplied as-is
        entry = {k: piece[k] for k in ('id', 'title', 'size', 'inches', 'kind', 'pdf', 'preview') if k in piece}
        entry.update({'facility': piece.get('facility', 'ajpvc'), 'group': piece.get('group', 'Other'), 'pages': []})
        out.append(entry)
        continue
    pages = []
    for pg in piece['pages']:
        src = open(os.path.join(ROOT, 'source', pg['file']), encoding='utf-8').read()
        w, h = page_size(src)
        body = map_assets(extract(src), pg['file'])
        # the location map slot
        body = re.sub(r'<div style="([^"]*)">\[LOCATION MAP\]</div>',
                      r'<div class="map-slot" style="\1">{{MAP}}</div>', body)
        for a, b in list(piece.get('tokens', {}).items()) + list(cfg['tokens'].items()):
            body = body.replace(a, b)
        # design tweaks ({{accent}} etc.) take their default value from the artboard's data-props
        dp = re.search(r"data-props='([^']*)'", src)
        props = json.loads(dp.group(1)) if dp else {}
        def tweak(m):
            p = props.get(m.group(1))
            if not isinstance(p, dict) or 'default' not in p:
                sys.exit(f'No default for {{{{{m.group(1)}}}}} in {pg["file"]}')
            return str(p['default'])
        body = re.sub(r'\{\{([a-z][A-Za-z0-9_]*)\}\}', tweak, body)
        pages.append({'label': pg['label'], 'w': w, 'h': h, 'html': body})
    entry = {k: piece[k] for k in ('id', 'title', 'size', 'inches')}
    entry['facility'] = piece.get('facility', 'ajpvc')
    if piece.get('kind'): entry['kind'] = piece['kind']
    if piece.get('duplex'): entry['duplex'] = True
    entry['group'] = piece.get('group', 'Other')
    entry['pages'] = pages
    out.append(entry)

js = '// Generated by tools/sync.py from the design canvas. Do not edit by hand.\nwindow.AJPVC_TEMPLATES = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n'
open(os.path.join(ROOT, 'js', 'templates.js'), 'w', encoding='utf-8').write(js)
left = sorted(set(re.findall(r'\[[A-Z0-9][A-Z0-9 ,:&;/\-]*\]', js)))
print(f'Wrote js/templates.js: {len(out)} pieces, {sum(len(p["pages"]) for p in out)} pages')
print('Placeholders still fixed in the designs:', ', '.join(left) or 'none')
